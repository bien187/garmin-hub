import { chromium } from "playwright";
const BASE = process.env.BASE_URL ?? "http://localhost:3000";
const browser = await chromium.launch({ args: ["--use-angle=swiftshader"] });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
let terrain = 0, basemap = 0;
page.on("response", (r) => {
  if (r.url().includes("elevation-tiles")) terrain++;
  if (r.url().includes("openfreemap.org/planet")) basemap++;
});
page.on("pageerror", (e) => console.log("[pageerror]", String(e).slice(0, 200)));
await page.goto(`${BASE}/login`);
await page.fill("input[type=password]", process.env.APP_PW);
await page.click("button[type=submit]");
await page.waitForURL(`${BASE}/`, { timeout: 20000 }).catch(() => {});
await page.goto(`${BASE}/activities/23572376914`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(12000);
const vorher = { terrain, basemap };
await page.getByRole("button", { name: /Flyover/ }).click();
await page.waitForTimeout(8000);
console.log("Tiles vor Play:", JSON.stringify(vorher), "— nach Play:", JSON.stringify({ terrain, basemap }));
await page.screenshot({ path: "/tmp/ghq-fly-fix.png" });
await browser.close();
