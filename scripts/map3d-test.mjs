import { chromium } from "playwright";
const browser = await chromium.launch({ args: ["--use-angle=swiftshader"] });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage();
await page.goto("https://garmin-hub.vercel.app/login");
await page.fill("input[type=password]", process.env.APP_PW);
await page.click("button[type=submit]");
await page.waitForURL("https://garmin-hub.vercel.app/", { timeout: 15000 }).catch(() => {});
await page.goto("https://garmin-hub.vercel.app/map", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(8000);
await page.locator('button[title="2D/3D"]').click();
await page.waitForTimeout(8000);
await page.screenshot({ path: "/tmp/ghq-map3d.png" });
await browser.close();
