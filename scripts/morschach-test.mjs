import { chromium } from "playwright";
const browser = await chromium.launch({ args: ["--use-angle=swiftshader"] });
const page = await (await browser.newContext({ viewport: { width: 900, height: 800 } })).newPage();
await page.goto("https://garmin-hub.vercel.app/login");
await page.fill("input[type=password]", process.env.APP_PW);
await page.click("button[type=submit]");
await page.waitForTimeout(4000);
await page.goto("https://garmin-hub.vercel.app/activities/23563223828", { waitUntil: "domcontentloaded" });
await page.waitForSelector("text=/wird vorgeladen/", { state: "detached", timeout: 45000 }).catch(() => console.log("Overlay blieb!"));
await page.waitForTimeout(1500);
await page.getByRole("button", { name: /Flyover/ }).click();
await page.waitForTimeout(5000);
await page.getByRole("button", { name: /Pause/ }).click();
await page.waitForTimeout(6000);
await page.screenshot({ path: "/tmp/ghq-morschach-fix.png" });
console.log("OK");
await browser.close();
